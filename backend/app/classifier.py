CATEGORY_KEYWORDS = {
    "Доступы": ["войти", "вход", "логин", "пароль", "доступ", "подписк",
                "аккаунт", "кабинет", "не пускает", "авториз"],
    "Корпоративная почта": ["письм", "почт", "спам", "email", "e-mail",
                            "имейл", "не приходит", "восстановлен"],
    "Программное обеспечение": ["ии-ассистент", "ассистент", "программ",
                                "приложени", "не запускается", "обновлен"],
    "Рабочее место": ["страниц", "сайт", "браузер", "белый экран", "тормоз",
                      "кэш", "cookie", "расширени", "компьютер", "ноутбук"],
    "Wi-Fi": ["wi-fi", "wifi", "вай-фай", "вайфай", "интернет", "видео",
              "загрузк", "обрыв", "медленно"],
    "VPN": ["vpn", "впн", "офисн", "корпоративн", "удален"],
    "Оборудование": ["звук", "микрофон", "наушник", "камер", "принтер",
                     "динамик", "колонок"],
}


def classify(text: str):
    t = text.lower()
    scores = {}
    for cat, kws in CATEGORY_KEYWORDS.items():
        hits = sum(1 for kw in kws if kw in t)
        if hits:
            scores[cat] = hits
    if not scores:
        return None, 0.0
    best = max(scores, key=scores.get)
    conf = min(0.97, 0.55 + 0.12 * scores[best])
    return best, round(conf, 2)